import AppKit
import Combine
import UniformTypeIdentifiers

/// The shelf: things you park in the notch to take somewhere else. Files and images dragged onto it,
/// text and links you paste into it, and (if you turn it on) a history of what you copy.
///
/// Dropped files stay where they are (the shelf keeps a reference); copied images are saved to a
/// temporary file so they can be dragged out like any file. Nothing is kept after the app quits.
final class ShelfStore: ObservableObject {
    struct Item: Identifiable, Equatable {
        enum Content: Equatable {
            case file(URL)
            case text(String)
            case link(URL)
        }

        let id = UUID()
        var content: Content
        var added = Date()
        var source: String?
        var temporary = false   // a file we created (copied image data); deleted when it leaves the shelf

        var title: String {
            switch content {
            case .file(let url): return url.lastPathComponent
            case .text(let text): return text.trimmingCharacters(in: .whitespacesAndNewlines).components(separatedBy: .newlines).first ?? text
            case .link(let url): return url.host ?? url.absoluteString
            }
        }

        var kindLabel: String {
            switch content {
            case .file(let url):
                if temporary { return "Image" }
                return (try? url.resourceValues(forKeys: [.localizedTypeDescriptionKey]))?.localizedTypeDescription ?? "File"
            case .text(let text): return text.count > 60 ? "Text · \(text.count) chars" : "Text"
            case .link: return "Link"
            }
        }

        var isImage: Bool {
            guard case .file(let url) = content else { return false }
            return UTType(filenameExtension: url.pathExtension)?.conforms(to: .image) ?? false
        }
    }

    @Published private(set) var items: [Item] = []
    /// Record everything you copy (needs macOS to allow reading the clipboard without asking).
    @Published private(set) var historyOn: Bool
    /// macOS lets ClaudeNotch read the clipboard without a prompt.
    @Published private(set) var historyAllowed = true
    @Published private(set) var copied: UUID?   // brief "Copied" on the item you clicked

    static let maxItems = 40
    private static let maxText = 50_000
    // Marked by password managers and similar apps as not for history (nspasteboard.org).
    private static let privateTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                       "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        .map { NSPasteboard.PasteboardType($0) }

    private let general: NSPasteboard
    private let defaults: UserDefaults
    private var lastChange: Int
    private var watcher: Timer?
    private let tempDir: URL
    private var thumbnails: [UUID: NSImage] = [:]

    init(pasteboard: NSPasteboard = .general, defaults: UserDefaults = .standard) {
        general = pasteboard
        self.defaults = defaults
        lastChange = pasteboard.changeCount
        historyOn = defaults.bool(forKey: "clipboardHistory")
        tempDir = FileManager.default.temporaryDirectory.appendingPathComponent("ClaudeNotchShelf")
        try? FileManager.default.removeItem(at: tempDir) // leftovers from the last run
        try? FileManager.default.createDirectory(at: tempDir, withIntermediateDirectories: true)
        refreshAllowed()
        updateWatcher()
    }

    // MARK: - Adding

    /// The "Paste" button: put whatever you copied last on the shelf.
    @discardableResult
    func pasteFromClipboard() -> Int {
        lastChange = general.changeCount
        return add(from: general, source: NSWorkspace.shared.frontmostApplication?.localizedName)
    }

    /// Files, images, links or text from a pasteboard (a drop, or the clipboard). Returns how many were added.
    @discardableResult
    func add(from pasteboard: NSPasteboard, source: String?) -> Int {
        var incoming: [Item] = []
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            incoming = urls.map { Item(content: .file($0), source: source) }
        } else if let image = imageFile(from: pasteboard) {
            incoming = [Item(content: .file(image), source: source, temporary: true)]
        } else if let urls = pasteboard.readObjects(forClasses: [NSURL.self]) as? [URL], let url = urls.first, url.scheme?.hasPrefix("http") == true {
            incoming = [Item(content: .link(url), source: source)]
        } else if let text = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines), !text.isEmpty {
            if let url = URL(string: text), url.scheme?.hasPrefix("http") == true, !text.contains(" ") {
                incoming = [Item(content: .link(url), source: source)]
            } else {
                incoming = [Item(content: .text(String(text.prefix(Self.maxText))), source: source)]
            }
        }
        for item in incoming.reversed() { insert(item) }
        return incoming.count
    }

    /// Newest first; the same thing twice just moves to the front.
    private func insert(_ item: Item) {
        if let existing = items.firstIndex(where: { $0.content == item.content }) {
            var moved = items.remove(at: existing)
            moved.added = Date()
            items.insert(moved, at: 0)
            if item.temporary, case .file(let url) = item.content { try? FileManager.default.removeItem(at: url) }
            return
        }
        items.insert(item, at: 0)
        while items.count > Self.maxItems { forget(items.removeLast()) }
    }

    /// Image data without a file (a screenshot to the clipboard, an image copied in a browser) → a temporary PNG.
    private func imageFile(from pasteboard: NSPasteboard) -> URL? {
        guard let type = pasteboard.availableType(from: [.png, .tiff]), let data = pasteboard.data(forType: type),
              data.count < 40_000_000 else { return nil }
        let png: Data
        if type == .png {
            png = data
        } else {
            guard let rep = NSBitmapImageRep(data: data), let converted = rep.representation(using: .png, properties: [:]) else { return nil }
            png = converted
        }
        let stamp = DateFormatter.localizedString(from: Date(), dateStyle: .none, timeStyle: .medium)
            .replacingOccurrences(of: ":", with: ".")
        let url = tempDir.appendingPathComponent("Image \(stamp) \(UUID().uuidString.prefix(4)).png")
        guard (try? png.write(to: url)) != nil else { return nil }
        return url
    }

    // MARK: - Using

    /// Put an item back on the clipboard, ready to paste anywhere.
    func copy(_ item: Item) {
        general.clearContents()
        switch item.content {
        case .file(let url): general.writeObjects([url as NSURL])
        case .text(let text): general.setString(text, forType: .string)
        case .link(let url):
            general.writeObjects([url as NSURL])
            general.setString(url.absoluteString, forType: .string)
        }
        lastChange = general.changeCount // our own write isn't something new to record
        copied = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            if self?.copied == item.id { self?.copied = nil }
        }
    }

    /// What gets dragged out of the notch into another app.
    func provider(for item: Item) -> NSItemProvider {
        switch item.content {
        case .file(let url):
            let provider = NSItemProvider(object: url as NSURL)
            provider.suggestedName = url.lastPathComponent
            return provider
        case .text(let text): return NSItemProvider(object: text as NSString)
        case .link(let url): return NSItemProvider(object: url as NSURL)
        }
    }

    func thumbnail(for item: Item) -> NSImage {
        if let cached = thumbnails[item.id] { return cached }
        let image: NSImage
        switch item.content {
        case .file(let url):
            if item.isImage, let full = NSImage(contentsOf: url) {
                image = Self.scaled(full, to: 96)
            } else {
                image = NSWorkspace.shared.icon(forFile: url.path)
            }
        case .text: image = NSImage(systemSymbolName: "text.alignleft", accessibilityDescription: "Text") ?? NSImage()
        case .link: image = NSImage(systemSymbolName: "link", accessibilityDescription: "Link") ?? NSImage()
        }
        thumbnails[item.id] = image
        return image
    }

    private static func scaled(_ image: NSImage, to side: CGFloat) -> NSImage {
        let size = image.size
        guard size.width > 0, size.height > 0 else { return image }
        let scale = side / max(size.width, size.height)
        let target = NSSize(width: size.width * scale, height: size.height * scale)
        let result = NSImage(size: target)
        result.lockFocus()
        image.draw(in: NSRect(origin: .zero, size: target))
        result.unlockFocus()
        return result
    }

    func remove(_ item: Item) {
        items.removeAll { $0.id == item.id }
        forget(item)
    }

    func clear() {
        items.forEach(forget)
        items.removeAll()
    }

    private func forget(_ item: Item) {
        thumbnails[item.id] = nil
        if item.temporary, case .file(let url) = item.content { try? FileManager.default.removeItem(at: url) }
    }

    // MARK: - Clipboard history

    func setHistory(_ on: Bool) {
        historyOn = on
        defaults.set(on, forKey: "clipboardHistory")
        lastChange = general.changeCount // start from now, not from whatever was copied before
        refreshAllowed()
        updateWatcher()
    }

    private func refreshAllowed() {
        if #available(macOS 15.4, *) {
            historyAllowed = general.accessBehavior == .alwaysAllow
        } else {
            historyAllowed = true
        }
    }

    private func updateWatcher() {
        watcher?.invalidate()
        watcher = nil
        guard historyOn else { return }
        let timer = Timer(timeInterval: 0.6, repeats: true) { [weak self] _ in self?.checkClipboard() }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        watcher = timer
    }

    /// The change counter can be read without touching the content (no privacy prompt). The content is
    /// read only when macOS allows it without asking, and never for items marked private.
    func checkClipboard() {
        guard historyOn else { return }
        let count = general.changeCount
        guard count != lastChange else {
            if !historyAllowed { refreshAllowed() } // you may have just allowed it in System Settings
            return
        }
        lastChange = count
        refreshAllowed()
        guard historyAllowed else { return }
        if let types = general.types, types.contains(where: Self.privateTypes.contains) { return }
        add(from: general, source: NSWorkspace.shared.frontmostApplication?.localizedName)
    }

    /// macOS lists an app under "Paste from Other Apps" only after it has asked once. Ask now (you
    /// clicked, so the system prompt makes sense), then open the setting so you can choose "Allow".
    func requestAccess() {
        _ = general.string(forType: .string)
        refreshAllowed()
        if !historyAllowed { Self.openPasteSettings() }
    }

    /// System Settings › Privacy & Security, where "Paste from Other Apps" lives.
    static func openPasteSettings() {
        let urls = ["x-apple.systempreferences:com.apple.preference.security?Privacy_Pasteboard",
                    "x-apple.systempreferences:com.apple.preference.security?Privacy"]
        for string in urls {
            if let url = URL(string: string), NSWorkspace.shared.open(url) { return }
        }
    }
}
